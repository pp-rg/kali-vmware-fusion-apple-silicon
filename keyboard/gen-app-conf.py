#!/usr/bin/env python3
"""Generate the keyd-application-mapper rules (app.conf) for a keyboard layout.

keyd names keys by their QWERTY *position*, so "the key labelled W" is `z` on AZERTY and `w` on QWERTY/QWERTZ.
Instead of hard-coding one layout, this reads the real XKB keymap and resolves, for the chosen layout:
  * which key produces a letter / digit / + / = / - and whether Shift is needed;
  * then writes the rules with the right key names.
Usage: gen-app-conf.py LAYOUT [VARIANT]  > ~/.config/keyd/app.conf        (needs setxkbmap + xkbcomp)
"""
import os, re, subprocess, sys, tempfile

# evdev code -> keyd key name (QWERTY position names)
KEYD = {41: 'grave', 12: 'minus', 13: 'equal', 26: 'leftbrace', 27: 'rightbrace', 39: 'semicolon',
        40: 'apostrophe', 43: 'backslash', 51: 'comma', 52: 'dot', 53: 'slash', 86: '102nd'}
for i, c in enumerate('1234567890'): KEYD[2 + i] = c
for code, row in ((16, 'qwertyuiop'), (30, 'asdfghjkl'), (44, 'zxcvbnm')):
    for i, c in enumerate(row): KEYD[code + i] = c

TERMINALS = ['qterminal', 'xfce4-terminal', 'gnome-terminal-server', 'kitty', 'alacritty']


def load_keymap(layout, variant):
    cmd = ['setxkbmap', '-layout', layout] + (['-variant', variant] if variant else []) + ['-print']
    spec = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    with tempfile.NamedTemporaryFile(suffix='.xkb', delete=False) as t:
        out = t.name
    try:
        subprocess.run(['xkbcomp', '-xkb', '-w0', '-', out], input=spec, text=True, capture_output=True, check=True)
        text = open(out).read()
    finally:
        os.unlink(out)
    codes = dict(re.findall(r'<(\w+)>\s*=\s*(\d+);', text.split('xkb_types')[0]))
    keys = {}   # keyd name -> keysym list (group 1)
    for name, body in re.findall(r'key <(\w+)>\s*\{(.*?)\};', text, re.S):
        m = re.search(r'symbols\[Group1\]\s*=\s*\[(.*?)\]', body, re.S)
        if name in codes and m and int(codes[name]) - 8 in KEYD:
            keys[KEYD[int(codes[name]) - 8]] = [s.strip() for s in m.group(1).split(',')]
    return keys


class Layout:
    def __init__(self, keys): self.keys = keys

    def find(self, sym):
        """-> (keyd key name, needs_shift) for a keysym; unshifted level preferred."""
        for lvl in (0, 1):
            for k, syms in self.keys.items():
                if len(syms) > lvl and syms[lvl] == sym: return k, bool(lvl)
        return None

    def pos(self, letter):
        r = self.find(letter)
        if not r or r[1]: sys.exit(f"layout has no unshifted key for '{letter}'")
        return r[0]

    def digit(self, d):
        """modifier prefix needed to type digit d on its row key ('' or 'S-'), or None if not reachable."""
        syms = self.keys.get(d, [])
        if syms[:1] == [d]: return ''
        if syms[1:2] == [d]: return 'S-'
        return None


def build(L):
    p = L.pos
    out = ["# Generated by keyboard/gen-app-conf.py - do not edit by hand (re-run the installer).",
           "# Key names are keyd (QWERTY position) names resolved from the XKB layout.", "",
           "# --- every application: Cmd + digit-row key 1..9 = tab 1..9 (browsers, file managers, editors, terminals).",
           "# Sent as Alt+digit, the Linux convention. Shift is added when the digit needs it (AZERTY: & é \" ...).",
           "[*]"]
    for d in '123456789':
        s = L.digit(d)
        if s is not None: out.append(f"cmd.{d} = A-{s}{d}")
    # LibreWolf/Firefox report two window classes
    rules = [
        f"cmd.{p('c')} = C-S-{p('c')}", f"cmd.{p('v')} = C-S-{p('v')}",
        f"cmd.{p('t')} = C-S-{p('t')}", f"cmd.{p('n')} = C-S-{p('t')}",      # new tab (Cmd+T, Cmd+N)
        f"cmd.{p('w')} = C-S-{p('w')}", f"cmd.{p('f')} = C-S-{p('f')}",      # close tab, find
        f"cmd.{p('k')} = C-{p('l')}",                                         # clear screen
        f"cmd.backspace = C-{p('u')}", "cmd.left = home", "cmd.right = end",
        f"option.left = A-{p('b')}", f"option.right = A-{p('f')}",
        "option.backspace = A-backspace", f"option.delete = A-{p('d')}",
        "shift.enter = A-enter",
        f"cmd+shift.{p('c')} = C-S-{p('c')}", f"cmd+shift.{p('v')} = C-S-{p('v')}",
    ]
    plus, equal, zero = L.find('plus'), L.find('equal'), L.digit('0')
    if plus and equal and not equal[1]:                       # zoom in on Cmd+=
        if plus[1] and plus[0] == equal[0]: rules.append(f"cmd.{equal[0]} = C-S-{equal[0]}")   # US/FR: + is Shift+=
        elif not plus[1] and plus[0] != equal[0]: rules.append(f"cmd.{equal[0]} = C-{plus[0]}")
    if zero:                                                   # zoom reset on Cmd+0 (Ctrl+0)
        rules += [f"cmd.0 = C-{zero}0", f"cmd+shift.0 = C-{zero}0"]
    for t in TERMINALS:
        out += ["", f"# --- terminal: {t}", f"[{t}]"] + rules
    return "\n".join(out) + "\n"


if __name__ == '__main__':
    if len(sys.argv) < 2: sys.exit(__doc__)
    layout = sys.argv[1]; variant = sys.argv[2] if len(sys.argv) > 2 else ''
    sys.stdout.write(build(Layout(load_keymap(layout, variant))))
